    /** Noktalama ve büyük harf farkını yok sayarak arar. */
    fun lookup(text: String): String? {
        val key = normalize(text)
        if (key.isEmpty()) return null
        return map[key]
    }

    private fun normalize(text: String): String {
        val sb = StringBuilder()
        for (ch in text.lowercase()) {
            when {
                ch.isLetter() || ch.isDigit() -> sb.append(ch)
                ch.isWhitespace() -> if (sb.isNotEmpty() && sb.last() != ' ') sb.append(' ')
                // kesme işareti ve noktalama atılır: "don't" → "dont"
            }
        }
        return sb.toString().trim()
    }
